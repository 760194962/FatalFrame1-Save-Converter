def _expand(runs):
    m = {}
    for s, d, n in runs:
        for k in range(n): m[s + k] = d + k
    return m
IDMAP = {('jp', 'us'): _expand(J2U), ('us', 'jp'): _expand(U2J)}
NFILES = {'jp': JP_FILES, 'us': US_FILES}

# ---- signature (XCalculateSignature, non-roamable)
def _h(k, d): return hmac.new(k, d, hashlib.sha1).digest()
SIG_KEY = _h(XBOX_CERT_KEY, TITLE_KEY)[:16]
def sign(data, hdkey): return _h(hdkey, _h(SIG_KEY, data))

def blocks():
    yield 0, HEADER
    o = HEADER + 20
    for _ in range(NBLOCK):
        yield o, BLOCK
        o += BLOCK + 20

def parse_hdkey(s):
    s = re.sub(r'[\s:-]', '', s or '')
    if not re.fullmatch(r'[0-9A-Fa-f]{32}', s): raise ValueError('HD key must be 32 hex digits')
    return bytes.fromhex(s)

def folder_name(name):
    """Save folder name = XCreateSaveGame hash of the save name."""
    P = (1 << 48) - 59; h = 0
    b = name.encode('utf-16-le')
    for i in range(0, len(b), 2): h = (h * 0x10000 + int.from_bytes(b[i:i + 2], 'little')) % P
    return '%012X' % h

def read_meta_name(path):
    try: t = open(path, 'rb').read().decode('utf-16')
    except (OSError, UnicodeError): return None
    m = re.search(r'Name=([^\r\n]*)', t)
    return m.group(1) if m else None

def meta_bytes(name): return ('﻿Name=%s\r\n' % name).encode('utf-16-le')

class Save:
    def __init__(self, folder):
        self.folder = folder
        files = {f.upper(): f for f in os.listdir(folder)}
        self.region = 'us' if 'G' in files else 'jp' if 'N' in files else None
        if not self.region: raise ValueError('no G or N file in %s' % folder)
        self.path = os.path.join(folder, files['G' if self.region == 'us' else 'N'])
        self.data = bytearray(open(self.path, 'rb').read())
        if len(self.data) != SAVE_SIZE: raise ValueError('%s: size %d, expected %d' % (self.path, len(self.data), SAVE_SIZE))
        self.name = read_meta_name(os.path.join(folder, files.get('SAVEMETA.XBX', 'SaveMeta.xbx')))
        self.image = os.path.join(folder, files['SAVEIMAGE.XBX']) if 'SAVEIMAGE.XBX' in files else None
    def slot(self):
        m = re.search(r'(\d+)', self.name or '')
        return int(m.group(1)) if m else None
    def checksum_ok(self): return struct.unpack_from('<I', self.data, 0)[0] == sum(self.data[4:HEADER]) & 0xFFFFFFFF
    def sig_ok(self, hdkey): return sum(sign(bytes(self.data[o:o + n]), hdkey) == self.data[o + n:o + n + 20] for o, n in blocks())
    def resources(self):
        out = []
        for i in range(RES_COUNT):
            p = RES_TABLE + 8 * i
            fid, typ = struct.unpack_from('<HB', self.data, p)
            if fid != 0xFFFF: out.append((i, fid, typ))
        return out

def find_saves(paths):
    found = []
    for p in paths:
        if not os.path.isdir(p): raise ValueError('not a folder: %s' % p)
        names = {f.upper() for f in os.listdir(p)}
        if 'G' in names or 'N' in names: found.append(p)
        else:
            for d in sorted(os.listdir(p)):
                q = os.path.join(p, d)
                if os.path.isdir(q) and {f.upper() for f in os.listdir(q)} & {'G', 'N'}: found.append(q)
    if not found: raise ValueError('no Fatal Frame save folders found')
    return found

def convert(save, to, src_key, dst_key, out_dir, slot=None, log=print, drop_res=()):
    """Returns the output folder. Raises ValueError on any problem; nothing is written then."""
    total = NBLOCK + 1
    ok = save.sig_ok(src_key) if src_key else total  # source key is optional: it only verifies the old signature
    if ok != total:
        raise ValueError('signature check failed (%d/%d blocks). Wrong source HD key, or not a JP/US save '
                         '(PAL saves are not supported).' % (ok, total))
    if not save.checksum_ok(): raise ValueError('header checksum is wrong; save is damaged')
    slot = slot or save.slot()
    if not slot: raise ValueError('cannot read the slot number from SaveMeta.xbx; give it with --slot')
    b = bytearray(save.data)
    changed = 0
    if save.region != to:
        m = IDMAP[(save.region, to)]
        for i, fid, typ in save.resources():
            if fid >= NFILES[save.region]: raise ValueError('resource %d: file id %#x out of range' % (i, fid))
            if fid not in m: raise ValueError('resource %d: file id %#x has no %s counterpart' % (i, fid, REGIONS[to]['label']))
            if m[fid] != fid:
                struct.pack_into('<H', b, RES_TABLE + 8 * i, m[fid]); changed += 1
        struct.pack_into('<I', b, 0, sum(b[4:HEADER]) & 0xFFFFFFFF)
    for i in drop_res:                      # experiment: forget loaded-resource entry i
        struct.pack_into('<H', b, RES_TABLE + 8 * i, 0xFFFF)
    if drop_res: struct.pack_into('<I', b, 0, sum(b[4:HEADER]) & 0xFFFFFFFF)
    for o, n in blocks(): b[o + n:o + n + 20] = sign(bytes(b[o:o + n]), dst_key)
    name = REGIONS[to]['name'] % slot
    od = os.path.join(out_dir, TITLE_ID, folder_name(name))
    if os.path.exists(od) and os.listdir(od): raise ValueError('output folder already exists and is not empty: %s' % od)
    os.makedirs(od, exist_ok=True)
    with open(os.path.join(od, REGIONS[to]['file']), 'wb') as f: f.write(b)
    with open(os.path.join(od, 'SaveMeta.xbx'), 'wb') as f: f.write(meta_bytes(name))
    if save.image: shutil.copyfile(save.image, os.path.join(od, 'saveimage.xbx'))
    log('%s [%s "%s"] -> %s [%s "%s"], %d file ids remapped' % (
        os.path.basename(save.folder), REGIONS[save.region]['label'], save.name, os.path.basename(od),
        REGIONS[to]['label'], name, changed))
    return od

def main(argv=None):
    ap = argparse.ArgumentParser(description='Fatal Frame (Xbox, 54430004) JP <-> US save converter v' + VERSION)
    sub = ap.add_subparsers(dest='cmd', required=True)
    a = sub.add_parser('info', help='show region, name and checks of save folders')
    a.add_argument('saves', nargs='+'); a.add_argument('--hdkey')
    c = sub.add_parser('convert', help='convert save folders')
    c.add_argument('saves', nargs='+')
    c.add_argument('--to', required=True, choices=['us', 'jp'])
    c.add_argument('--hdkey', help='HD key of the source console (optional; only verifies the old signature)')
    c.add_argument('--dst-hdkey', help='HD key of the target console (default: same as --hdkey; one of the two is required)')
    c.add_argument('--out', default='converted', help='output folder (default: ./converted)')
    c.add_argument('--drop-res', help='EXPERIMENT: forget these loaded-resource entries, e.g. 0-18 or 7-18 or 9,13,14,18')
    c.add_argument('--slot', type=int, help='slot number to use for the new save name')
    args = ap.parse_args(argv)
    try:
        saves = [Save(p) for p in find_saves(args.saves)]
        if args.cmd == 'info':
            key = parse_hdkey(args.hdkey) if args.hdkey else None
            for s in saves:
                print('%s\n  region %s, file %s, name "%s", slot %s, folder name expected %s' % (
                    s.folder, REGIONS[s.region]['label'], os.path.basename(s.path), s.name, s.slot(),
                    folder_name(s.name) if s.name else '?'))
                print('  header checksum %s' % ('ok' if s.checksum_ok() else 'BAD'))
                if key: print('  signature %d/%d blocks ok with this HD key' % (s.sig_ok(key), NBLOCK + 1))
                print('  loaded files: %s' % ' '.join('%#x' % f for i, f, t in s.resources()))
            return 0
        src = parse_hdkey(args.hdkey) if args.hdkey else None
        dst = parse_hdkey(args.dst_hdkey) if args.dst_hdkey else src
        if not dst: raise ValueError('give --dst-hdkey (or --hdkey if the target console is the same)')
        drop = ()
        if args.drop_res:
            drop = []
            for part in args.drop_res.split(','):
                a, _, z = part.partition('-'); drop += range(int(a), int(z or a) + 1)
            if not 0 <= min(drop) <= max(drop) < RES_COUNT: raise ValueError('--drop-res must be within 0-%d' % (RES_COUNT - 1))
        for s in saves: convert(s, args.to, src, dst, args.out, args.slot, drop_res=drop)
        return 0
    except ValueError as e:
        print('error: %s' % e, file=sys.stderr); return 1

if __name__ == '__main__':
    sys.exit(main())
